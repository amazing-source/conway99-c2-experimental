"""Stage 1 of the mixture campaign (note 43) in a CLOUD session, without the big leaf files: each orientation's leaves are
regenerated by the v6 filter (deterministic: same code, same order as logs/mix6_cls_<ci>_S_0.json), then the per-leaf
pair-level LP (pair_fast.FastPair, MAXBB=0: LP only, certificate cache) runs on a leaf range.
  gen  <ci> <rep>                -> data/cloud_leaves/<ci>_<rep>.json.gz  {ci, rep, In, A, done, leaves}
  plan <chunk> <ci>...           -> prints 'run <ci> <rep> <lo> <hi>' for every generated no-A orientation with leaves
  run  <ci> <rep> <lo> <hi>      -> logs/cloud_stage1/<ci>_<rep>_<lo>_<hi>.json  {counts, open leaf indices, sample check}
  reps <ci>...                   -> prints 'gen <ci> <rep>' for every orientation class of the class (insertion order)
'rep' = index of the orientation class in mix_filter6.run's own order; locally, job j of class ci = the j-th rep WITH leaves.
Every 20th dead leaf (env SAMPLE) is re-checked with structures' model and checker (general_model.build + certify.check).
Setup: repo conway99-c2-experimental + external_structures/ (clone of conway99-structures-lab), pip: numpy scipy highspy networkx"""
import sys, os, json, gzip, time, glob
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
import mix_filter6 as F
N = 7


def nreps(ci):
    twE = F.twisted_classes()[ci]; auts = F.automorphisms2(twE, []); keys = set()
    for In, tw in F.orientations2(twE, []):
        arcs = [(a, b) for b in range(N) for a in In[b]]
        keys.add(min(tuple(sorted((g[a], g[b]) for a, b in arcs)) for g in auts))
    return twE, len(keys)


def gen(ci, rep):
    out = "data/cloud_leaves/%d_%d.json.gz" % (ci, rep)
    if os.path.exists(out): return
    os.makedirs("data/cloud_leaves", exist_ok=True)
    twE, K = nreps(ci)
    reps, surv, stats, done, per_orient = F.run(twE, rep, K, float(os.environ.get('BUDGET', 30000)))
    assert len(per_orient) == 1, len(per_orient)
    po = per_orient[0]
    json.dump({"ci": ci, "rep": rep, "In": po["In"], "A": po["A"], "done": done,
               "leaves": [list(map(list, L)) for L in po["leaves"]]}, gzip.open(out + ".tmp", "wt"))
    os.replace(out + ".tmp", out)
    print("GEN %d %d: %d leaves A=%s done=%s" % (ci, rep, len(po["leaves"]), po["A"], done))


def run(ci, rep, lo, hi):
    import numpy as np
    import pair_fast as PF
    d = json.load(gzip.open("data/cloud_leaves/%d_%d.json.gz" % (ci, rep), "rt"))
    assert d["done"] and d["A"] is None
    In = {int(c): v for c, v in d["In"].items()}
    leaves = [[tuple(z) for z in L] for L in d["leaves"]][lo:hi]
    asg = [{c: tuple(z for z in L if z[0] == c) for c in range(N)} for L in leaves]
    t0 = time.time(); Fp = PF.FastPair(In, asg); openl = []; dead = 0; checked = 0; bad = 0
    step = int(os.environ.get('SAMPLE', 20))
    from general_model import build
    from certify import check
    import pair_verify_leaves as PV
    for t, a in zip(range(lo, hi), asg):
        Fp.set_leaf(a); r = Fp.certify(maxnodes=0)
        if r['status'] != 'dead': openl.append(t); continue
        dead += 1
        if dead % step == 1:                       # independent re-check of a sample with structures' model and checker
            orbs = PV.canonical_skeleton(In, leaves[t - lo])
            A_, lo_, hi_, lb, ub = build(orbs)[:5]
            ok = check(A_, lo_, hi_, lb, ub, PV.dense_tree(Fp.export_tree(r['tree']), A_.shape[0]))
            checked += 1; bad += not ok
    os.makedirs("logs/cloud_stage1", exist_ok=True)
    rec = {"ci": ci, "rep": rep, "In": d["In"], "range": [lo, hi], "dead": dead, "open": openl, "checked": checked,
           "invalid": bad, "secs": round(time.time() - t0)}
    json.dump(rec, open("logs/cloud_stage1/%d_%d_%d_%d.json" % (ci, rep, lo, hi), "w"))
    print("RUN %d %d [%d,%d): dead %d open %d checked %d invalid %d %ds" % (ci, rep, lo, hi, dead, len(openl), checked, bad, rec["secs"]))


if __name__ == "__main__":
    sys.path.insert(0, os.environ.get('STRUCT_AD', (os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'external_structures', 'ad') if os.path.isdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'external_structures', 'ad')) else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'vendor_structures'))))
    cmd = sys.argv[1]
    if cmd == "reps":
        for ci in map(int, sys.argv[2:]):
            for rep in range(nreps(ci)[1]): print("gen %d %d" % (ci, rep))
    elif cmd == "gen": gen(int(sys.argv[2]), int(sys.argv[3]))
    elif cmd == "plan":
        chunk = int(sys.argv[2])
        for ci in map(int, sys.argv[3:]):
            for fn in sorted(glob.glob("data/cloud_leaves/%d_*.json.gz" % ci), key=lambda f: int(f.split("_")[-1].split(".")[0])):
                d = json.load(gzip.open(fn, "rt"))
                if d["A"] is not None or not d["leaves"]: continue
                n = len(d["leaves"])
                for lo in range(0, n, chunk):
                    if not os.path.exists("logs/cloud_stage1/%d_%d_%d_%d.json" % (ci, d["rep"], lo, min(n, lo + chunk))):
                        print("run %d %d %d %d" % (ci, d["rep"], lo, min(n, lo + chunk)))
    elif cmd == "run": run(*map(int, sys.argv[2:6]))
